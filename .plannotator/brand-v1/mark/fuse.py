"""Connect the Blank letters the way Rerun's wordmark connects (reference/rerun/mark/wordmark-trim.png).

    node (exports letters.json from blank3.js + as.js + ks.js), then
    /tmp/blankword/.venv/bin/python fuse.py > blank-fused.js

The letters keep their shapes. They are set with no gap, so neighbours fuse into one slab, and
every stretch where two letters touch is marked at both ends with Rerun's tick: a hairline
(6.5 of 240, Rerun's 14 px at 515) that runs into the join for 19 and ends round. Where a
chamfer meets the next stem, the V notch stays open and the hairline continues past its tip.
"""

import json
import sys

from shapely import affinity
from shapely.geometry import LineString, Point, Polygon, box
from shapely.ops import unary_union
from svgelements import Close, Line, Move, Path

H = 240
HW = 6.5  # hairline width
D = 19  # how far a tick runs into the join
GAP = float(sys.argv[1]) if len(sys.argv) > 1 else 0.0


def letter(d):
    """SVG path (evenodd) -> shapely geometry, by XOR-ing its subpaths."""
    g = Polygon()
    for sub in Path(d).as_subpaths():
        pts = []
        for seg in Path(sub):  # keep exact corners; sample only the curved segments
            if isinstance(seg, (Line, Close, Move)):
                if seg.end is not None:
                    pts.append((seg.end.x, seg.end.y))
            else:
                pts += [(q.x, q.y) for q in (seg.point(i / 32) for i in range(1, 33))]
        poly = Polygon(pts).buffer(0)
        g = g.symmetric_difference(poly)
    return g


def contacts(left, right, x):
    """y intervals where both letters have material against the line x."""
    out, start, step = [], None, 0.25
    y = 0.0
    while y <= H:
        both = left.contains(Point(x - 0.6, y)) and right.contains(Point(x + 0.6, y))
        if both and start is None:
            start = y
        if not both and start is not None:
            out.append((start, y - step))
            start = None
        y += step
    if start is not None:
        out.append((start, H))
    return out


def tick(x, y_from, y_to):
    """Hairline from y_from (open side) to y_to, round at y_to, square past the open side."""
    back = -HW if y_to > y_from else HW
    return LineString([(x, y_from + back), (x, y_to)]).buffer(HW / 2, cap_style="round", quad_segs=24)


letters = json.load(open("letters.json"))
shapes, x = [], 0.0
for L in letters:
    shapes.append(affinity.translate(letter(L["d"]), x, 0))
    x += L["w"] + GAP
width = x - GAP

word = unary_union(shapes)
cuts, report = [], []
x = 0.0
for i in range(len(letters) - 1):
    x += letters[i]["w"] + GAP
    if GAP:
        continue
    for y0, y1 in contacts(shapes[i], shapes[i + 1], x):
        report.append((round(x, 1), y0, y1))
        if y0 > 0.5:
            cuts.append(tick(x, y0, min(y0 + D, (y0 + y1) / 2)))
        if y1 < H - 0.5:
            cuts.append(tick(x, y1, max(y1 - D, (y0 + y1) / 2)))
word = word.difference(unary_union(cuts)) if cuts else word
word = word.intersection(box(0, 0, width, H))

polys = list(word.geoms) if word.geom_type == "MultiPolygon" else [word]
ring = lambda c: "M" + "L".join(f"{px:.2f} {py:.2f}" for px, py in list(c.coords)[:-1]) + "Z"
d = " ".join(ring(p.exterior) + "".join(ring(h) for h in p.interiors) for p in polys)
print("// generated by fuse.py, do not edit")
print(f"// joins (x, y0, y1): {report}")
print(f"const FUSED = {json.dumps({'width': round(width, 2), 'height': H, 'path': d})};")
