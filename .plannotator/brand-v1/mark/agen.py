"""a variants for the Blank wordmark (blank3.js, X = 40). Prints JS: `const AS = {name: {w, d}}`.

    /tmp/blankword/.venv/bin/python agen.py > as.js

Two-story a. Its lower bowl is B's lower bowl mirrored (top at 105, mid bar 30, counter 104 x 65
with the round end away from the stem, bottom bar 40, 40 chamfers on the bowl side). Above it a
hook bar, and between them an opening running out to the left that ends round at the stem.
"""

import json

from shapely.geometry import Point, Polygon, box

H, S, T, MID, C, IC, X = 240, 62, 40, 30, 40, 22, 40
CH, R0 = 65, 32.5
AW = 52 + 104 + S
XS = AW - S  # stem left edge
YB = T + CH  # bowl top, B's mid bar top (105)


def chamfered(x0, y0, x1, y1, tl=0, tr=0, br=0, bl=0):
    return Polygon([(x0, y0 + tl), (x0 + tl, y0), (x1 - tr, y0), (x1, y0 + tr), (x1, y1 - br), (x1 - br, y1),
                    (x0 + bl, y1), (x0, y1 - bl)])


def a(hb, tl, tr, terminal="flat", round_end=True, hx=0):
    """hb: hook bar thickness. tl/tr: top-left / top-right chamfers. terminal: how the hook ends.
    hx: where the hook bar starts; shorter than the bowl so the top does not overhang."""
    g = chamfered(0, X, AW, H, tl=tl, tr=tr, br=IC, bl=C)
    if hx:
        g = g.difference(box(-1, X - 1, hx, X + hb))
        g = g.difference(Polygon([(hx - 1, X - 1), (hx + tl, X - 1), (hx, X + tl), (hx - 1, X + tl)]))  # new end keeps its corner
    top = X + hb
    gap = YB - top
    # the opening between hook and bowl, open to the left, round where it meets the stem
    cut = box(-1, top, XS - (gap / 2 if round_end else 0), YB)
    if round_end:
        cut = cut.union(Point(XS - gap / 2, top + gap / 2).buffer(gap / 2, quad_segs=32))
    g = g.difference(cut)
    # the bowl's own top-left chamfer below the opening
    g = g.difference(Polygon([(-1, YB - 1), (C, YB - 1), (C, YB), (0, YB + C), (-1, YB + C)]))
    if terminal == "chamfer":  # hook end cut at 45 degrees underneath, like Rerun's r terminal
        g = g.difference(Polygon([(-1, top + 1), (-1, X + 2), (hb - 2, top + 1)]))
    # B's counter, mirrored: flat on the stem side, round end on the left
    y0 = YB + MID
    cx = AW - (AW - S + 10) + R0
    counter = box(cx, y0, XS, y0 + CH).union(Point(cx, y0 + R0).buffer(R0, quad_segs=48))
    return g.difference(counter)


def octagon_a(c=C, hb=30, aw=AW, wall=52):
    """The a as one octagon (all four corners chamfered c), like Rerun's e. Inside: a counter like
    B's (65 tall, round end away from the stem) at the bottom, and above it a slot that runs out to
    the left and ends round at the stem. aw: letter width (n is 189); wall: bowl wall on the left."""
    xs = aw - S
    g = chamfered(0, X, aw, H, tl=c, tr=c, br=c, bl=c)
    top = X + hb
    gap = YB - top
    slot = box(-1, top, xs - gap / 2, YB).union(Point(xs - gap / 2, top + gap / 2).buffer(gap / 2, quad_segs=32))
    y0 = YB + MID
    cx = wall + R0
    counter = box(cx, y0, xs, y0 + CH).union(Point(cx, y0 + R0).buffer(R0, quad_segs=48))
    return g.difference(slot).difference(counter)


def path(g):
    polys = list(g.geoms) if g.geom_type == "MultiPolygon" else [g]
    ring = lambda c: "M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in list(c.coords)[:-1]) + "Z"
    return " ".join(ring(p.exterior) + "".join(ring(i) for i in p.interiors) for p in polys)


V = {
    "a1": a(30, IC, C),  # n's shoulder chamfer at top-right, 35 opening ending round at the stem
    "a2": a(30, IC, IC),  # same, the I's small corner at top-right
    "a3": a(30, 0, C, terminal="chamfer"),  # hook end cut underneath at 45 degrees
    "a4": a(40, IC, C),  # heavier hook (40, as B's top bar), 25 opening
    "a5": a(30, IC, C, hx=52),  # hook starts over the counter's left edge
    "a6": a(30, IC, C, hx=84.5),  # hook starts over the centre of the counter's round end
    "a7": octagon_a(),  # octagon, chamfers 40 (B's)
    "a9": octagon_a(aw=2 * S + 65),  # as wide as the n (189), bowl wall 52, counter 75
    "a10": octagon_a(aw=2 * S + 65, wall=46),  # as wide as the n, thinner wall, counter 81
    "a8": octagon_a(c=56),  # octagon, larger chamfers (Rerun's e runs ~0.27 of its height)
}
out = {name: {"w": round(g.bounds[2], 2), "d": path(g)} for name, g in V.items()}
print("// generated by agen.py")
print(f"const AS = {json.dumps(out)};")
