"""k variants for the Blank wordmark (blank3.js, X = 40). Prints JS: `const KS = {name: {w, d}}`.

    /tmp/blankword/.venv/bin/python kgen.py > ks.js

A k is an ascender stem plus two 45 degree arms meeting it in the middle of the x-height. To
match the other letters, the inside corners (the V between the arms, the crotches at the stem)
are rounded the way the B's counters are, and the arm tips are cut off blunt instead of ending
in spikes.
"""

import json

from shapely.geometry import Polygon, box

H, S, IC, X = 240, 62, 22, 40
YM = (X + H) / 2
H2 = (H - X) / 2


def k(aw, v, kw, rv, cut, slit=False):
    """aw: arm width measured horizontally. v: x of the V tip past the stem. kw: letter width.
    rv: radius for the inside corners. cut: height of the vertical cut on the arm tips."""
    u = aw - v
    stem = Polygon([(0, 0), (S - IC, 0), (S, IC), (S, H), (0, H)])
    up = Polygon([(S - 1, YM - u), (S + H2 - u, X), (S + H2 + v, X), (S + v, YM), (S - 1, YM)])
    lo = Polygon([(S - 1, YM + u), (S + H2 - u, H), (S + H2 + v, H), (S + v, YM), (S - 1, YM)])
    g = stem.union(up).union(lo).buffer(0)
    # round the inside corners: closing (grow then shrink) fills sharp concave corners with arcs
    if rv:
        g = g.buffer(rv, join_style="round", quad_segs=32).buffer(-rv, join_style="round", quad_segs=32)
        g = g.intersection(box(0, 0, 10_000, H))
        # the closing also rounds the stem's own outer corners back in, so restore the stem
        g = g.union(stem)
    # clip to the letter width; the arm tips become vertical cuts of height about `cut`
    g = g.intersection(box(0, 0, kw, H))
    if slit:  # BI's slit where the upper arm meets the stem, at the x-height
        cx, w, depth = S + 12, 20, 19
        from shapely.geometry import Point
        sl = box(cx - w / 2, X - 1, cx + w / 2, X + depth - w / 2).union(Point(cx, X + depth - w / 2).buffer(w / 2, 32))
        g = g.difference(sl)
    return g


def path(g):
    polys = list(g.geoms) if g.geom_type == "MultiPolygon" else [g]
    ring = lambda c: "M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in list(c.coords)[:-1]) + "Z"
    return " ".join(ring(p.exterior) + "".join(ring(i) for i in p.interiors) for p in polys)


# k4/k5: openings sized off the n. The upper opening is 65 wide at the x-height (n's counter)
# and the upper arm reaches the stem at y = 105 (B's mid bar), so u = 35.
V = {
    "was": k(84, 37.8, 199.8, 0, 0),
    "k4": k(80, 45, 189, 16, 0),
    "k5": k(72, 37, 183, 16, 0),
    "k6": k(72, 37, 183, 16, 0, slit=True),
}
out = {name: {"w": round(g.bounds[2], 2), "d": path(g)} for name, g in V.items()}
print("// generated by kgen.py")
print(f"const KS = {json.dumps(out)};")
