"""Optical sizes of the Blank wordmark, after Rerun's 07-logo_sizes: smaller cuts are heavier and simpler.

    /tmp/blankword/.venv/bin/python sizes.py   -> sizes.js (const SIZES)

Built from the approved wordmark's own parts (mark/rand.py, RAND.B: B and l from letters.json,
a_bowl(cw=110, r=80), n_arch(cw=110), k_arms(kw=204), gap 22), letter by letter:
  1. simpler: below a size, the ticks (B, a, n) and the k's arm slots are filled in, because a
     20-unit slot closes up on screen and in print before the letter does
  2. heavier: each letter is grown by d units with mitred joins, so stems, bars and walls all gain
     2d and the 45 degree chamfers stay at 45 degrees; counters lose 2d
  3. spacing: the visible gap between letters opens up
  4. the word is scaled back to the 240 cap height, so every cut is the same size and only the
     weight, detail and spacing differ
"""

import json
import os
import sys

from shapely import affinity
from shapely.geometry import Point, box
from shapely.ops import unary_union

HERE = os.path.dirname(os.path.abspath(__file__))
MARK = os.path.join(HERE, "..", "..", "mark")
sys.path.insert(0, MARK)
os.chdir(MARK)  # rand.py reads letters.json from the working directory
import rand  # noqa: E402

H, S = rand.H, rand.S

# the five letters of RAND.B with the slot shapes that each one carries
a_g, a_w = rand.a_bowl(cw=110, r=80)
n_g, n_w = rand.n_arch(cw=110)
k_g, k_w = rand.k_arms(kw=204)


def slot_fill(cx, w=22, depth=21):
    """Fills a tick (20 wide, 19 deep, round end) cut from the top edge."""
    return box(cx - w / 2, -1, cx + w / 2, depth)


def k_slots_fill(arm=78):
    ym = H / 2
    y_end = ym - arm * 0.62 + 11
    top = box(S - 1, -1, S + 21, y_end)
    return [top, affinity.scale(top, 1, -1, origin=(0, ym))]


LETTERS = [
    (rand.B[0], rand.B[1], [slot_fill(74)]),
    (rand.L[0], rand.L[1], []),
    (a_g, a_w, [slot_fill(a_w - S - 10)]),
    (n_g, n_w, [slot_fill(S + 10)]),
    (k_g, k_w, k_slots_fill()),
]

# name, grow d, visible gap, fill the slots
CUTS = [
    ("display", 0, 22, False),
    ("large", 3, 28, False),
    ("medium", 6, 36, True),
    ("small", 10, 46, True),
    ("micro", 14, 58, True),
]


def cut(d, gap, simple):
    shapes, x = [], 0.0
    for g, w, fills in LETTERS:
        if simple and fills:
            g = unary_union([g, *fills]).intersection(box(0, 0, w, H))
        if d:
            g = g.buffer(d, join_style=2, mitre_limit=4)
        shapes.append(affinity.translate(g, x + d, 0))
        x += w + 2 * d + gap
    word = unary_union(shapes)
    minx, miny, maxx, maxy = word.bounds
    word = affinity.translate(word, -minx, -miny)
    s = H / (maxy - miny)
    word = affinity.scale(word, s, s, origin=(0, 0))
    return word, (maxx - minx) * s


if __name__ == "__main__":
    out = []
    for name, d, gap, simple in CUTS:
        g, w = cut(d, gap, simple)
        out.append({"name": name, "grow": d, "gap": gap, "simple": simple, "width": round(w, 2), "height": H, "path": rand.path(g)})
    with open(os.path.join(HERE, "sizes.js"), "w") as f:
        f.write("// generated by sizes.py, do not edit\nconst SIZES = " + json.dumps(out) + ";\n")
    print([(o["name"], o["width"]) for o in out])
